function getBrowserLanguage() {
    const saved = localStorage.getItem("dg_lang");
    if (saved && SUPPORTED_LANGUAGES[saved]) {
        return saved;
    }
    const browserLangs = navigator.languages || [navigator.language || navigator.userLanguage || "en"];
    for (let lang of browserLangs) {
        if (!lang) continue;
        const code = lang.toLowerCase().split("-")[0];
        if (SUPPORTED_LANGUAGES[code]) {
            return code;
        }
    }
    return "en";
}

function setLanguage(langCode) {
    if (!SUPPORTED_LANGUAGES[langCode]) {
        langCode = "en";
    }

    localStorage.setItem("dg_lang", langCode);
    document.documentElement.lang = langCode;

    if (SUPPORTED_LANGUAGES[langCode].dir === "rtl") {
        document.documentElement.setAttribute("dir", "rtl");
        document.body.classList.add("rtl-layout");
    } else {
        document.documentElement.removeAttribute("dir");
        document.body.classList.remove("rtl-layout");
    }

    const dict = I18N[langCode] || I18N["en"];

    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        if (dict[key]) {
            el.textContent = dict[key];
        }
    });

    document.querySelectorAll("[data-i18n-html]").forEach(el => {
        const key = el.getAttribute("data-i18n-html");
        if (dict[key]) {
            el.innerHTML = dict[key];
        }
    });

    updateLangSelectorUI(langCode);
}

function renderLanguageSelector() {
    const header = document.querySelector(".system-panel .panel-right");
    if (!header) return;
    if (document.getElementById("lang-selector-widget")) return;

    const currentLang = getBrowserLanguage();

    const widget = document.createElement("div");
    widget.id = "lang-selector-widget";
    widget.className = "lang-selector-widget";

    let optionsHtml = "";
    for (let [code, info] of Object.entries(SUPPORTED_LANGUAGES)) {
        optionsHtml += `<option value="${code}" ${code === currentLang ? "selected" : ""}>${info.flag} ${info.native}</option>`;
    }

    widget.innerHTML = `
        <span class="lang-icon">🌐</span>
        <select id="lang-select" class="lang-dropdown" onchange="setLanguage(this.value)">
            ${optionsHtml}
        </select>
    `;

    header.insertBefore(widget, header.firstChild);
}

function updateLangSelectorUI(langCode) {
    const select = document.getElementById("lang-select");
    if (select) {
        select.value = langCode;
    }
}

document.addEventListener("DOMContentLoaded", () => {
    renderLanguageSelector();
    const initialLang = getBrowserLanguage();
    setLanguage(initialLang);
});
